/// Media and system keys, by HID consumer usage, with RMK's name.
pub const CONSUMER: &[(u16, &str)] = &[
    (0x00E2, "AudioMute"),
    (0x00E9, "AudioVolUp"),
    (0x00EA, "AudioVolDown"),
    (0x00B5, "MediaNextTrack"),
    (0x00B6, "MediaPrevTrack"),
    (0x00B7, "MediaStop"),
    (0x00CD, "MediaPlayPause"),
    (0x006F, "BrightnessUp"),
    (0x0070, "BrightnessDown"),
];

/// RMK's name for a keyboard usage.
pub fn name(usage: u16) -> Option<&'static str> {
    KEYS.iter()
        .find(|(u, _)| *u == usage)
        .map(|(_, name)| *name)
}

/// RMK's name for a consumer usage.
pub fn consumer(usage: u16) -> Option<&'static str> {
    CONSUMER
        .iter()
        .find(|(u, _)| *u == usage)
        .map(|(_, name)| *name)
}
