//! RMK firmware: a layout written as an RMK keymap, and the project that
//! builds it.
//!
//! RMK is configured by a `keyboard.toml`. The half of that file about the
//! hardware is data, in the board definition; this crate adds the keymap
//! and the files around it. Bindings are translated to RMK's key actions,
//! and one RMK has nothing for is reported, never dropped.

pub mod keys;

use kc_boards::board::{FirmwareProfile, RmkFlavor, RmkProfile, Side};
use kc_boards::Board;
use kc_model::{
    BehaviorRef, Binding, KeyExpr, LayerId, Location, Param, Problem, Project, Severity,
};
use kc_zmk::keycodes::{keycodes, UsagePage};
use kc_zmk::Modifier;

/// The first line of every generated file.
const NOTICE: &str =
    "Generated by Keyboard Curator. Change the board or the layout there, not this file.";

/// The UF2 family of an nRF52840 with the Adafruit bootloader, for halves
/// whose board does not name its own.
const NRF52840_FAMILY: u32 = 0xADA5_2840;

fn modifier_name(modifier: Modifier) -> &'static str {
    match modifier {
        Modifier::LCtrl => "LCtrl",
        Modifier::LShift => "LShift",
        Modifier::LAlt => "LAlt",
        Modifier::LGui => "LGui",
        Modifier::RCtrl => "RCtrl",
        Modifier::RShift => "RShift",
        Modifier::RAlt => "RAlt",
        Modifier::RGui => "RGui",
    }
}

/// RMK's name for a key with nothing implied, such as `A` or `LShift`.
fn plain_key(expr: &KeyExpr) -> Option<&'static str> {
    let key = keycodes().get(&expr.key)?;
    (expr.mods.is_empty() && key.implicit_mods.is_empty() && key.page == UsagePage::Keyboard)
        .then(|| keys::name(key.usage))
        .flatten()
}

/// A key press as an RMK action: a bare name, or `WM(key, mods)`.
fn key_action(expr: &KeyExpr) -> Result<String, String> {
    let key = keycodes()
        .get(&expr.key)
        .ok_or_else(|| format!("`{}` is not a key this app knows", expr.key))?;
    let mods: Vec<&str> = expr
        .mods
        .iter()
        .chain(&key.implicit_mods)
        .map(|m| modifier_name(*m))
        .collect();
    let name = match key.page {
        UsagePage::Keyboard => keys::name(key.usage),
        UsagePage::Consumer if mods.is_empty() => keys::consumer(key.usage),
        _ => None,
    }
    .ok_or_else(|| format!("RMK has no key for `{}`", expr.key))?;
    Ok(if mods.is_empty() {
        name.to_string()
    } else {
        format!("WM({name}, {})", mods.join(" | "))
    })
}

fn layer_index(layer: LayerId, layers: &[LayerId]) -> Result<usize, String> {
    layers
        .iter()
        .position(|l| *l == layer)
        .ok_or_else(|| "the layer no longer exists".to_string())
}

/// The RMK key action for a binding. `layers` is the layout's layers in
/// order, and `ble_profiles` how many Bluetooth profiles the firmware
/// keeps. Fails, with the reason, for a binding RMK has nothing for.
pub fn action(binding: &Binding, layers: &[LayerId], ble_profiles: u8) -> Result<String, String> {
    let (label, params) = match binding {
        Binding::Raw { .. } => {
            return Err("devicetree text means nothing to RMK".into());
        }
        Binding::Behavior {
            behavior: BehaviorRef::BuiltIn(label),
            params,
        } => (label.as_str(), params.as_slice()),
        Binding::Behavior { .. } => {
            return Err("behaviors defined in the layout are not translated to RMK yet".into());
        }
    };
    let layer = |layer: &LayerId| layer_index(*layer, layers);
    // RMK's wireless keys are numbered after its profiles.
    let profiles = u32::from(ble_profiles);
    Ok(match (label, params) {
        ("trans", []) => "_".into(),
        ("none", []) => "No".into(),
        ("kp", [Param::Key(expr)]) => key_action(expr)?,
        ("mo", [Param::Layer(l)]) => format!("MO({})", layer(l)?),
        ("to", [Param::Layer(l)]) => format!("TO({})", layer(l)?),
        ("tog", [Param::Layer(l)]) => format!("TG({})", layer(l)?),
        ("sl", [Param::Layer(l)]) => format!("OSL({})", layer(l)?),
        ("sk", [Param::Key(expr)]) => match plain_key(expr) {
            Some(name)
                if name.ends_with("Ctrl")
                    || name.ends_with("Shift")
                    || name.ends_with("Alt")
                    || name.ends_with("Gui") =>
            {
                format!("OSM({name})")
            }
            _ => return Err("in RMK a sticky key can only be a single modifier".into()),
        },
        ("mt", [Param::Key(hold), Param::Key(tap)]) => {
            let hold = plain_key(hold).ok_or("in RMK a mod-tap holds a single modifier")?;
            format!("MT({}, {hold})", key_action(tap)?)
        }
        ("lt", [Param::Layer(l), Param::Key(tap)]) => {
            format!("LT({}, {})", layer(l)?, key_action(tap)?)
        }
        ("bootloader", []) => "Bootloader".into(),
        ("sys_reset", []) => "Reboot".into(),
        ("caps_word", []) => "CapsWordToggle".into(),
        ("key_repeat", []) => "Repeat".into(),
        ("mkp", [Param::Constant(button)]) => match button.as_str() {
            "LCLK" | "MB1" => "MouseBtn1".into(),
            "RCLK" | "MB2" => "MouseBtn2".into(),
            "MCLK" | "MB3" => "MouseBtn3".into(),
            "MB4" => "MouseBtn4".into(),
            "MB5" => "MouseBtn5".into(),
            other => return Err(format!("RMK has no mouse button for `{other}`")),
        },
        ("bt", [Param::Command { name, args }]) => match (name.as_str(), args.as_slice()) {
            ("BT_SEL", [profile]) if *profile < profiles => {
                format!("User{profile}")
            }
            ("BT_SEL", _) => {
                return Err(format!(
                    "this RMK firmware keeps {profiles} Bluetooth profiles"
                ));
            }
            ("BT_NXT", []) => format!("User{profiles}"),
            ("BT_PRV", []) => format!("User{}", profiles + 1),
            ("BT_CLR", []) => format!("User{}", profiles + 2),
            _ => return Err(format!("RMK has nothing for &bt {name}")),
        },
        ("out", [Param::Command { name, .. }]) if name == "OUT_TOG" => {
            format!("User{}", profiles + 3)
        }
        _ => return Err(format!("RMK has nothing for &{label}")),
    })
}

/// Whether a binding can be written as an RMK key action.
pub fn expressible(binding: &Binding, project: &Project, profile: &RmkProfile) -> bool {
    let layers: Vec<LayerId> = project.layers.iter().map(|l| l.id).collect();
    action(binding, &layers, profile.ble_profiles).is_ok()
}

/// What stops a layout from being built as RMK firmware.
pub fn check(project: &Project, profile: &RmkProfile) -> Vec<Problem> {
    let layers: Vec<LayerId> = project.layers.iter().map(|l| l.id).collect();
    let mut problems = Vec::new();
    let mut error = |location: Location, message: String| {
        problems.push(Problem {
            severity: Severity::Error,
            location,
            message,
        });
    };
    if profile.layers > 0 && project.layers.len() > profile.layers {
        error(
            Location::Project,
            format!(
                "the layout has {} layers, and this firmware holds {}",
                project.layers.len(),
                profile.layers
            ),
        );
    }
    for layer in &project.layers {
        for (position, binding) in layer.bindings.iter().enumerate() {
            if let Err(reason) = action(binding, &layers, profile.ble_profiles) {
                error(
                    Location::Key {
                        layer: layer.id,
                        position,
                    },
                    reason,
                );
            }
        }
    }
    for combo in &project.combos {
        if let Err(reason) = combo_entry(project, combo, &layers, profile) {
            error(Location::Combo(combo.id), reason);
        }
    }
    problems
}

/// One combo as an entry of RMK's combo list. RMK identifies a combo's
/// keys by what they do on the layer it applies to, not by position.
fn combo_entry(
    project: &Project,
    combo: &kc_model::features::Combo,
    layers: &[LayerId],
    profile: &RmkProfile,
) -> Result<String, String> {
    let on = match combo.layers.as_slice() {
        [] => None,
        [only] => Some(layer_index(*only, layers)?),
        _ => return Err("in RMK a combo applies to one layer or to all of them".into()),
    };
    let layer = &project.layers[on.unwrap_or(0)];
    let mut actions = Vec::new();
    for position in &combo.key_positions {
        let binding = layer
            .bindings
            .get(*position)
            .ok_or("the combo uses a key the layout does not have")?;
        let key = action(binding, layers, profile.ble_profiles)
            .map_err(|reason| format!("one of the combo's keys cannot be used in RMK: {reason}"))?;
        if key == "_" || key == "No" {
            return Err("in RMK a combo's keys must each do something on its layer".into());
        }
        actions.push(format!("\"{key}\""));
    }
    let output = action(&combo.binding, layers, profile.ble_profiles)?;
    let layer = on.map_or_else(String::new, |index| format!(", layer = {index}"));
    Ok(format!(
        "  {{ actions = [{}], output = \"{output}\"{layer} }},",
        actions.join(", ")
    ))
}

/// The keymap half of `keyboard.toml`: the layers, and the combos.
pub fn keymap(project: &Project, profile: &RmkProfile) -> Result<String, String> {
    let layers: Vec<LayerId> = project.layers.iter().map(|l| l.id).collect();
    let declared = project.layers.len().max(profile.layers);
    let mut out = format!("[keymap]\nlayers = {declared}\n");
    for layer in &project.layers {
        // The layer's name, kept out of anything RMK would have to parse.
        let name: String = layer
            .name
            .chars()
            .map(|c| if c.is_control() { ' ' } else { c })
            .collect();
        out.push_str(&format!("\n# {name}\n[[keymap.layer]]\nkeys = \"\"\"\n"));
        let mut actions = Vec::with_capacity(layer.bindings.len());
        for binding in &layer.bindings {
            actions.push(action(binding, &layers, profile.ble_profiles)?);
        }
        for row in actions.chunks(6) {
            out.push_str(&row.join("  "));
            out.push('\n');
        }
        out.push_str("\"\"\"\n");
    }
    // Layers the firmware counts on that the layout does not have let the
    // ones below show through.
    let keys = project.layers.first().map_or(0, |l| l.bindings.len());
    for number in project.layers.len()..declared {
        out.push_str(&format!(
            "\n# Unused layer {}\n[[keymap.layer]]\nkeys = \"\"\"\n",
            number + 1
        ));
        for row in vec!["_"; keys].chunks(6) {
            out.push_str(&row.join("  "));
            out.push('\n');
        }
        out.push_str("\"\"\"\n");
    }
    if !project.combos.is_empty() {
        let timeout = project
            .combos
            .iter()
            .filter_map(|c| c.timeout_ms)
            .max()
            .unwrap_or(50);
        out.push_str(&format!(
            "\n[behavior.combo]\ntimeout = \"{timeout}ms\"\ncombos = [\n"
        ));
        for combo in &project.combos {
            out.push_str(&combo_entry(project, combo, &layers, profile)?);
            out.push('\n');
        }
        out.push_str("]\n");
    }
    Ok(out)
}

fn side_name(side: Side) -> &'static str {
    match side {
        Side::Left => "left",
        Side::Right => "right",
    }
}

/// The name of the firmware file for one half, such as `imprint_left.uf2`.
pub fn artifact_name(profile: &FirmwareProfile, side: Side) -> String {
    format!("{}_{}.uf2", profile.config_name, side_name(side))
}

/// How a git revision is named in a Cargo dependency: a full commit hash
/// as `rev`, anything else as a tag.
fn cargo_pin(revision: &str) -> String {
    if revision.len() == 40 && revision.chars().all(|c| c.is_ascii_hexdigit()) {
        format!("rev = \"{revision}\"")
    } else {
        format!("tag = \"{revision}\"")
    }
}

