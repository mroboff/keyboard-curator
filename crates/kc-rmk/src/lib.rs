/// Turns a raw firmware image into a UF2 file. Kept in the generated
/// repository so that the start address and family ID are this board's.
const UF2_PY: &str = r#"#!/usr/bin/env python3
"""Wraps a raw firmware image as a UF2 file: tools/uf2.py in.bin out.uf2 --base 0x26000 --family 0xADA52840"""
import argparse
import struct

parser = argparse.ArgumentParser()
parser.add_argument("source")
parser.add_argument("target")
parser.add_argument("--base", type=lambda v: int(v, 0), required=True)
parser.add_argument("--family", type=lambda v: int(v, 0), required=True)
args = parser.parse_args()

with open(args.source, "rb") as file:
    image = file.read()
chunks = [image[i : i + 256] for i in range(0, len(image), 256)]
with open(args.target, "wb") as file:
    for number, chunk in enumerate(chunks):
        header = struct.pack(
            "<IIIIIIII",
            0x0A324655,
            0x9E5D5157,
            0x00002000,  # the family ID is present
            args.base + number * 256,
            256,
            number,
            len(chunks),
            args.family,
        )
        file.write(header + chunk.ljust(476, b"\0") + struct.pack("<I", 0x0AB16F30))
print(f"{args.target}: {len(chunks)} blocks from {args.base:#x}, family {args.family:#x}")
"#;

/// The files of a firmware repository that builds RMK for `project`.
/// Paths are relative to the repository's root.
pub fn generate(
    project: &Project,
    board: &Board,
    profile: &FirmwareProfile,
) -> Result<Vec<(String, String)>, String> {
    let rmk = profile
        .rmk
        .as_ref()
        .ok_or("this firmware has no RMK build described")?;
    let keymap = keymap(project, rmk)?;
    let central = board
        .halves
        .iter()
        .find(|h| h.central)
        .ok_or("the board has no central half")?;
    let peripheral = board.halves.iter().find(|h| !h.central);
    let family = |half: &kc_boards::board::Half| half.uf2_family.unwrap_or(NRF52840_FAMILY);
    // Central first: which binary goes on which half, and its family.
    let mut images = vec![("central", central.side, family(central))];
    if let Some(half) = peripheral {
        images.push(("peripheral", half.side, family(half)));
    }
    let mut files: Vec<(String, String)> = Vec::new();
    let mut file = |path: &str, contents: String| files.push((path.to_string(), contents));

    match rmk.flavor {
        RmkFlavor::Upstream => {
            file(
                "keyboard.toml",
                format!("# {NOTICE}\n\n{}\n\n{keymap}", rmk.hardware.trim()),
            );
            file(
                "Cargo.toml",
                format!(
                    r#"# {NOTICE}
[package]
name = "{name}-rmk"
version = "0.1.0"
edition = "2024"
publish = false

[workspace]

[dependencies]
rmk = {{ git = "{url}", {pin}, default-features = false, features = ["defmt", "storage", "watchdog", "nrf52840_ble", "split", "async_matrix", "adafruit_bl"] }}
nrf-sdc = {{ version = "0.4.0", features = ["defmt", "peripheral", "central", "nrf52840"] }}
nrf-mpsl = {{ version = "0.4.0", features = ["defmt", "critical-section-impl", "nrf52840"] }}
bt-hci = {{ version = "0.10", features = ["defmt"] }}
cortex-m = "0.7.7"
cortex-m-rt = "0.7.5"
embassy-time = {{ version = "0.5", features = ["tick-hz-32_768", "defmt", "defmt-timestamp-uptime"] }}
embassy-nrf = {{ version = "0.11", features = ["defmt", "nrf52840", "time-driver-rtc1", "gpiote", "unstable-pac", "nfc-pins-as-gpio", "time"] }}
embassy-executor = {{ version = "0.10", features = ["defmt", "platform-cortex-m", "executor-thread"] }}
defmt = "1"
defmt-rtt = "1"
panic-probe = {{ version = "1", features = ["print-defmt"] }}
static_cell = "2"

[[bin]]
name = "central"
path = "src/central.rs"

[[bin]]
name = "peripheral"
path = "src/peripheral.rs"

[profile.release]
codegen-units = 1
debug = true
lto = "fat"
opt-level = "z"
overflow-checks = false
"#,
                    name = profile.config_name,
                    url = rmk.source.url,
                    pin = cargo_pin(&rmk.source.revision),
                ),
            );
            file(
                ".cargo/config.toml",
                format!(
                    "# {NOTICE}\n[build]\ntarget = \"thumbv7em-none-eabihf\"\n\n[env]\nDEFMT_LOG = \"off\"\nKEYBOARD_TOML_PATH = {{ value = \"keyboard.toml\", relative = true }}\n"
                ),
            );
            // The vendor's flash layout: the firmware starts where the
            // vendor's does and stops short of the vendor's settings.
            file(
                "memory.x",
                format!(
                    "/* {NOTICE} */\nMEMORY\n{{\n  FLASH : ORIGIN = {:#010x}, LENGTH = {:#010x}\n  RAM : ORIGIN = 0x20000008, LENGTH = 255K\n}}\n",
                    rmk.flash_origin, rmk.flash_length
                ),
            );
            file("build.rs", BUILD_RS.to_string());
            file(
                "src/central.rs",
                "#![no_main]\n#![no_std]\n\nuse rmk::macros::rmk_central;\n\n#[rmk_central]\nmod keyboard_central {}\n".into(),
            );
            file(
                "src/peripheral.rs",
                "#![no_main]\n#![no_std]\n\nuse rmk::macros::rmk_peripheral;\n\n#[rmk_peripheral(id = 0)]\nmod keyboard_peripheral {}\n".into(),
            );
            file("tools/uf2.py", UF2_PY.to_string());
            let mut convert = String::new();
            for (binary, side, family) in &images {
                convert.push_str(&format!(
                    "          \"$OBJCOPY\" -O binary target/thumbv7em-none-eabihf/release/{binary} {binary}.bin\n          python3 tools/uf2.py {binary}.bin {} --base {:#x} --family {family:#x}\n",
                    artifact_name(profile, *side),
                    rmk.flash_origin,
                ));
            }
            file(
                ".github/workflows/build.yml",
                format!(
                    r#"# {NOTICE}
name: Build RMK firmware
on: [push, pull_request, workflow_dispatch]

jobs:
  build:
    runs-on: ubuntu-24.04
    steps:
      - uses: actions/checkout@v4
      - name: Install the toolchain
        run: |
          sudo apt-get update
          sudo apt-get install -y gcc-arm-none-eabi
          rustup toolchain install stable --profile minimal --component llvm-tools
          rustup default stable
          rustup target add thumbv7em-none-eabihf
      - name: Build
        run: cargo build --release
      - name: Make the UF2 files
        run: |
          OBJCOPY="$(find "$(rustc --print sysroot)" -name llvm-objcopy | head -1)"
{convert}      - uses: actions/upload-artifact@v4
        with:
          name: firmware
          path: "*.uf2"
"#
                ),
            );
        }
        RmkFlavor::MoergoRmk => {
            // That firmware has its own project for the board, with the
            // hardware, lighting and touchpads set up. Only the keymap is
            // ours: it is spliced over the one in its keyboard.toml.
            file("keymap.toml", format!("# {NOTICE}\n\n{keymap}"));
            file("tools/splice_keymap.py", SPLICE_PY.to_string());
            file(
                ".github/workflows/build.yml",
                format!(
                    r#"# {NOTICE}
name: Build RMK firmware
on: [push, pull_request, workflow_dispatch]

jobs:
  build:
    runs-on: ubuntu-24.04
    steps:
      - uses: actions/checkout@v4
      - name: Fetch the firmware this keymap is built into
        run: |
          git clone {url} firmware
          git -C firmware checkout {revision}
          git -C firmware submodule update --init --recursive
      - name: Put this keymap into it
        run: python3 tools/splice_keymap.py keymap.toml firmware/{dir}/keyboard.toml
      - uses: cachix/install-nix-action@v25
      - name: Build
        run: cd firmware && nix develop --command just go60-firmware
      - uses: actions/upload-artifact@v4
        with:
          name: firmware
          path: firmware/dist/**/*.uf2
"#,
                    url = rmk.source.url,
                    revision = rmk.source.revision,
                    dir = rmk.project_dir,
                ),
            );
        }
    }
    Ok(files)
}

/// Replaces the keymap in a firmware project's `keyboard.toml` with ours:
/// everything from `[keymap]` up to the next section that is not part of
/// the keymap or the combos.
const SPLICE_PY: &str = r#"#!/usr/bin/env python3
"""Replaces the keymap of a keyboard.toml: tools/splice_keymap.py keymap.toml keyboard.toml"""
import re
import sys

ours = open(sys.argv[1]).read()
target = open(sys.argv[2]).read()
ours_keymap = ours[ours.index("[keymap]") :]

# The combos, if we have any, replace theirs; otherwise theirs stay.
combo = re.search(r"^\[behavior\.combo\]\n.*?(?=^\[|\Z)", ours_keymap, re.S | re.M)
ours_layers = ours_keymap[: combo.start()] if combo else ours_keymap

start = target.index("[keymap]")
after = re.compile(r"^\[(?!keymap\]|\[keymap\.layer\]\])", re.M).search(target, start + 1)
end = after.start() if after else len(target)
target = target[:start] + ours_layers.rstrip() + "\n\n" + target[end:]

if combo:
    theirs = re.search(r"^\[behavior\.combo\]\n.*?(?=^\[|\Z)", target, re.S | re.M)
    if theirs:
        target = target[: theirs.start()] + combo.group(0) + target[theirs.end() :]
    else:
        target = target.rstrip() + "\n\n" + combo.group(0)

open(sys.argv[2], "w").write(target)
print(f"spliced {ours_layers.count('[[keymap.layer]]')} layers into {sys.argv[2]}")
"#;
